"""The two endpoints: read a shared headline, contribute one.

Reading is open to any signed-in user. Writing is restricted to an explicit
allowlist, which is what makes it safe to accept article bodies from clients —
and accepting them from clients is itself deliberate, because a server that
fetched articles from its own datacentre address would be trivial for the
publishers to block.
"""

import datetime
import logging
from typing import Annotated

from fastapi import APIRouter, Depends, Header, HTTPException, Response
from pydantic import BaseModel, Field
from starlette.requests import Request
from starlette.status import (
    HTTP_400_BAD_REQUEST,
    HTTP_401_UNAUTHORIZED,
    HTTP_403_FORBIDDEN,
    HTTP_404_NOT_FOUND,
    HTTP_429_TOO_MANY_REQUESTS,
    HTTP_503_SERVICE_UNAVAILABLE,
)

from klikintappaja_api._db import Database, Headline
from klikintappaja_api.articles import (
    MalformedArticleIdError,
    UnknownSiteError,
    content_hash,
    parse_article_ref,
)
from klikintappaja_api.auth import Caller, InvalidTokenError, TokenVerifier, bearer_token
from klikintappaja_api.ratelimit import READ_QUOTA, WRITE_QUOTA, Quota

# Mirrors the extension: MAX_OUT_CHARS in background.js, and the 120-character
# floor content.js uses to decide an article yielded enough text to be worth
# rewriting. A locked article returns only its lede and falls under it.
MAX_HEADLINE_CHARS = 300
MIN_BODY_CHARS = 120

logger = logging.getLogger(__name__)
router = APIRouter(prefix='/v1/headlines', tags=['headlines'])


class Contribution(BaseModel):
    """A headline generated by a contributor with their own API key."""

    headline: str = Field(min_length=1, max_length=MAX_HEADLINE_CHARS)
    body: str = Field(min_length=1)
    provider: str = Field(min_length=1, max_length=40)
    model: str = Field(min_length=1, max_length=80)
    original_headline: str | None = Field(default=None, max_length=500)
    paywalled: bool = False


class HeadlineResponse(BaseModel):
    """What a client gets back for an article."""

    id: str
    headline: str
    sha: str
    model: str
    generated_at: datetime.datetime


def get_database(request: Request) -> Database:
    """Provide the shared database handle."""
    return request.app.state.db


def get_verifier(request: Request) -> TokenVerifier:
    """Provide the shared token verifier."""
    return request.app.state.verifier


DbDep = Annotated[Database, Depends(get_database)]


async def get_caller(
    request: Request,
    authorization: Annotated[str | None, Header()] = None,
) -> Caller:
    """Authenticate the request from its Google ID token."""
    verifier: TokenVerifier = request.app.state.verifier
    try:
        return await verifier.verify(bearer_token(authorization))
    except InvalidTokenError as exc:
        raise HTTPException(
            status_code=HTTP_401_UNAUTHORIZED,
            detail=str(exc),
            headers={'WWW-Authenticate': 'Bearer'},
        ) from exc


CallerDep = Annotated[Caller, Depends(get_caller)]


async def _enforce_quota(db: Database, caller: Caller, quota: Quota) -> None:
    now = datetime.datetime.now(datetime.UTC)
    within = await db.consume_quota(caller.user_key, quota.window_for(now), quota.limit, quota.window_seconds)
    if not within:
        raise HTTPException(
            status_code=HTTP_429_TOO_MANY_REQUESTS,
            detail=f'{quota.name} quota exceeded, try again later',
            headers={'Retry-After': str(quota.window_seconds)},
        )


def _resolve(site: str, article_id: str) -> str:
    try:
        return parse_article_ref(site, article_id).article_id
    except (MalformedArticleIdError, UnknownSiteError) as exc:
        # A path we cannot parse cannot name a stored headline either.
        raise HTTPException(status_code=HTTP_404_NOT_FOUND, detail=str(exc)) from exc


def _as_response(headline: Headline) -> HeadlineResponse:
    return HeadlineResponse(
        id=headline.article_id,
        headline=headline.headline,
        sha=headline.sha,
        model=headline.model,
        generated_at=headline.generated_at,
    )


@router.get('/{site}/{article_id}', response_model=HeadlineResponse)
async def read_headline(
    site: str,
    article_id: str,
    db: DbDep,
    caller: CallerDep,
    response: Response,
    if_none_match: Annotated[str | None, Header()] = None,
) -> HeadlineResponse | Response:
    """Return the current shared headline for an article.

    The body fingerprint is served as the `ETag`, so a client holding a version
    can revalidate with `If-None-Match` and get a `304` when nothing changed.
    Unlike the publishers' own ETags, this one tracks the article text.
    """
    key = _resolve(site, article_id)
    await _enforce_quota(db, caller, READ_QUOTA)

    stored = await db.get_headline(key)
    if stored is None:
        raise HTTPException(status_code=HTTP_404_NOT_FOUND, detail='no contributed headline for this article')

    etag = f'"{stored.sha}"'
    if if_none_match and etag in {tag.strip() for tag in if_none_match.split(',')}:
        return Response(status_code=304, headers={'ETag': etag})

    response.headers['ETag'] = etag
    return _as_response(stored)


@router.post('/{site}/{article_id}', response_model=HeadlineResponse)
async def contribute_headline(
    site: str,
    article_id: str,
    contribution: Contribution,
    db: DbDep,
    caller: CallerDep,
    response: Response,
) -> HeadlineResponse:
    """Accept a headline generated by an approved contributor.

    The fingerprint is computed here from the submitted body; a client-supplied
    hash is never trusted. The body is used for that and then discarded.
    """
    key = _resolve(site, article_id)

    if not await db.is_contributor(caller.user_key):
        raise HTTPException(
            status_code=HTTP_403_FORBIDDEN,
            detail='contributing is limited to approved accounts',
        )

    await _enforce_quota(db, caller, WRITE_QUOTA)

    if contribution.paywalled:
        raise HTTPException(
            status_code=HTTP_400_BAD_REQUEST,
            detail='headlines derived from paywalled articles are not shared',
        )
    if len(contribution.body) < MIN_BODY_CHARS:
        raise HTTPException(
            status_code=HTTP_400_BAD_REQUEST,
            detail=f'article body must be at least {MIN_BODY_CHARS} characters',
        )

    sha = content_hash(contribution.body)
    stored = await db.get_headline(key)
    if stored is not None and stored.sha == sha:
        # Same article text: whatever is stored already describes it. Re-visits
        # are therefore free and cannot churn `generated_at`.
        response.headers['ETag'] = f'"{stored.sha}"'
        return _as_response(stored)

    headline = Headline(
        article_id=key,
        headline=contribution.headline.strip(),
        sha=sha,
        provider=contribution.provider,
        model=contribution.model,
        contributor=caller.user_key,
        generated_at=datetime.datetime.now(datetime.UTC),
    )
    await db.put_headline(headline)
    logger.info('stored headline for %s (sha %s)', key, sha)
    response.headers['ETag'] = f'"{sha}"'
    return _as_response(headline)


health_router = APIRouter(tags=['ops'])


@health_router.get('/healthz')
async def health(db: DbDep) -> dict:
    """Report whether the database is reachable."""
    try:
        return await db.ping()
    except Exception as exc:
        logger.warning('database ping failed: %s', exc)
        raise HTTPException(status_code=HTTP_503_SERVICE_UNAVAILABLE) from exc
